# Частина 4, задача 3: журнал подій, найновіші зверху,
# події однієї секунди — у порядку надходження.
events = [
    (10, "A"), (12, "B"), (12, "C"), (11, "D"), (12, "E"), (10, "F"),
]  # (секунда, повідомлення) у порядку надходження

# Стабільне сортування за секундою зі спаданням:
# reverse=True зберігає порядок надходження для рівних ключів.
result = sorted(events, key=lambda e: e[0], reverse=True)
print(result)
# [(12,'B'), (12,'C'), (12,'E'), (11,'D'), (10,'A'), (10,'F')]
