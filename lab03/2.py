"""
Задача 2. Підсумки за місяцями.

Підсумок за кожен місяць рахуємо в масиві фіксованого розміру (12 елементів).
Номер місяця слугує індексом напряму — перебору в пошуках "свого" місяця немає.
"""

MONTHS_IN_YEAR = 12


def monthly_totals(operations):
    """
    operations — список кортежів (month, amount), де month у діапазоні 1..12.
    Повертає масив фіксованого розміру з 12 підсумків (індекс 0 -> січень).
    """
    totals = [0.0] * MONTHS_IN_YEAR  # масив фіксованого розміру, а не список

    for month, amount in operations:
        totals[month - 1] += amount  # номер місяця напряму слугує індексом

    return totals


def main():
    operations = [
        (1, 1200.0),
        (3, 450.5),
        (3, 300.0),
        (7, 999.99),
        (7, 1.01),
        (12, 5000.0),
        (1, 200.0),
    ]

    totals = monthly_totals(operations)

    month_names = [
        "Січень", "Лютий", "Березень", "Квітень", "Травень", "Червень",
        "Липень", "Серпень", "Вересень", "Жовтень", "Листопад", "Грудень",
    ]

    print("Підсумки за місяцями:")
    for i in range(MONTHS_IN_YEAR):
        print(f"  {month_names[i]:10s}: {totals[i]:.2f}")


if __name__ == "__main__":
    main()
